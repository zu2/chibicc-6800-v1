int ulp_diff(float a, float b)
{
  union {
    float f;
    int32_t i;
  } ua = {a}, ub = {b};

  if (ua.i < 0) {
    ua.i = 0x80000000 - ua.i;
  }
  if (ub.i < 0) {
    ub.i = 0x80000000 - ub.i;
  }
  return abs(ua.i - ub.i);
}

int max_ulp_tolerance(float x)
{
  float a = fabsf(x);
  // Below pi/4 the reduction drops out, so only the polynomial rounds
  if (a < 0.7853981f) {
    return 1;
  }
  return 2;
}

#define ARRAY_SIZE(arr) (sizeof(arr) / sizeof(arr[0]))

int main(int argc, char **argv)
{
  int n_diff = 0;
  int n_fail = 0;
  int total = (int)ARRAY_SIZE(patterns);

  printf("%-12s %-12s %-12s %-8s %-8s\n", "input", "expected", "got", "ULP",
         "result");

  for (size_t i = 0; i < ARRAY_SIZE(patterns); ++i) {
    float result = cosf(patterns[i].input);
    float expected = patterns[i].cos_expected;
    int ulp = ulp_diff(result, expected);
    int max_ulp = max_ulp_tolerance(patterns[i].input);

    const char *res_msg = "PASS";
    if (expected == 0.0f) {
      if (result != 0.0f || signbit(expected) != signbit(result)) {
        res_msg = "FAIL";
        n_fail++;
      }
    } else if (isnan(expected)) {
      if (!isnan(result)) {
        res_msg = "FAIL";
        n_fail++;
      }
    } else if (ulp > max_ulp) {
      res_msg = "DIFF";
      n_diff++;
    }

    printf("%-12e %-12e %-12e %-8d %-8s\n", patterns[i].input, expected, result,
           ulp, res_msg);
  }

  printf("\nTotal tests: %d\n", total);
  if (n_diff == 0 && n_fail == 0) {
    printf("All tests passed.\n");
  } else {
    printf("%d FAIL, %d DIFF\n", n_fail, n_diff);
  }
  return n_fail != 0 || n_diff != 0;
}
