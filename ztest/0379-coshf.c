static uint32_t ulp_diff(float a, float b)
{
  uint32_t ia, ib;

  memcpy(&ia, &a, sizeof(ia));
  memcpy(&ib, &b, sizeof(ib));

  if (ia & 0x80000000u)
    ia = 0x80000000u - (ia & 0x7fffffffu);
  if (ib & 0x80000000u)
    ib = 0x80000000u - (ib & 0x7fffffffu);

  return ia > ib ? ia - ib : ib - ia;
}

static int same_float(float a, float b)
{
  if (isnan(a) || isnan(b))
    return isnan(a) && isnan(b);

  if (a != b)
    return 0;

  return a != 0.0f || signbit(a) == signbit(b);
}

int main(void)
{
  int n_diff = 0;
  int n_fail = 0;

  for (size_t i = 0; i < sizeof(exact_patterns) / sizeof(exact_patterns[0]); i++) {
    float input = exact_patterns[i].input;
    float expected = exact_patterns[i].expected;
    float result = coshf(input);

    if (!same_float(result, expected)) {
      printf("%-12e %-12e %-12e FAIL\n", input, expected, result);
      n_fail++;
    }
  }

  for (size_t i = 0; i < sizeof(patterns) / sizeof(patterns[0]); i++) {
    float input = patterns[i].input;
    float expected = patterns[i].expected;
    float result = coshf(input);
    uint32_t ulp = ulp_diff(result, expected);

    if (signbit(result) || isnan(result)) {
      printf("%-12e %-12e %-12e FAIL\n", input, expected, result);
      n_fail++;
    } else if (ulp > 1) {
      printf("%-12e %-12e %-12e %-8lu DIFF\n",
             input, expected, result, (unsigned long)ulp);
      n_diff++;
    }
  }

  printf("Total tests: %u, %d differ, %d failed\n",
         (unsigned)(sizeof(exact_patterns) / sizeof(exact_patterns[0]) +
                    sizeof(patterns) / sizeof(patterns[0])),
         n_diff, n_fail);

  return n_fail != 0 || n_diff != 0;
}
