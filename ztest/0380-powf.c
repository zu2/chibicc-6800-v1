static int32_t ulp_diff(float a, float b)
{
  int32_t ia = *(int32_t *)&a;
  int32_t ib = *(int32_t *)&b;

  if (ia < 0)
    ia = 0x80000000 - ia;
  if (ib < 0)
    ib = 0x80000000 - ib;

  return ia > ib ? ia - ib : ib - ia;
}

static int same_float(float a, float b)
{
  if (isnan(a) || isnan(b))
    return isnan(a) && isnan(b);

  if (a != b)
    return 0;

  return a != 0.0f || signbit(a) == signbit(b);
}

// powf multiplies the relative error of log2 x by |y * log2 x|, which is the
// exponent of the result. log2f is off by up to 3.01 ulp over its whole
// reduced range and the one multiply rounds by 0.5, so the factor is
// ln2 * 3.51 = 2.43, rounded up to 2.5 here.
// ilogbf truncates, so |y * log2 x| can be one larger than it reports.
// A flat bound would let the whole range through untested.
static int32_t ulp_limit(float expected)
{
  int e = ilogbf(expected);

  if (e < 0) {
    e = -e;
  }

  return 1 + (int32_t)((long)(e + 1) * 5 / 2);
}

int main(void)
{
  int n_diff = 0;
  int n_fail = 0;

  for (size_t i = 0; i < sizeof(exact_patterns) / sizeof(exact_patterns[0]); i++) {
    float base = exact_patterns[i].base;
    float exponent = exact_patterns[i].exponent;
    float expected = exact_patterns[i].expected;
    float result = powf(base, exponent);

    if (!same_float(result, expected)) {
      printf("%-12e %-12e %-12e %-12e FAIL\n", base, exponent, expected, result);
      n_fail++;
    }
  }

  for (size_t i = 0; i < sizeof(patterns) / sizeof(patterns[0]); i++) {
    float base = patterns[i].base;
    float exponent = patterns[i].exponent;
    float expected = patterns[i].expected;
    float result = powf(base, exponent);
    int32_t ulp = ulp_diff(result, expected);

    if (isnan(result) || isinf(result) || signbit(result) != signbit(expected)) {
      printf("%-12e %-12e %-12e %-12e FAIL\n", base, exponent, expected, result);
      n_fail++;
    } else if (ulp > ulp_limit(expected)) {
      printf("%-12e %-12e %-12e %-12e %-8ld DIFF\n",
             base, exponent, expected, result, (long)ulp);
      n_diff++;
    }
  }

  printf("Total tests: %u, %d differ, %d failed\n",
         (unsigned)(sizeof(exact_patterns) / sizeof(exact_patterns[0]) +
                    sizeof(patterns) / sizeof(patterns[0])),
         n_diff, n_fail);

  return n_fail != 0 || n_diff != 0;
}
